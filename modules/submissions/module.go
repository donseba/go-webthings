//go:embed templates translations
var files embed.FS

// Module adds a Submissions instance. key is used in URLs of the admin and the
// form action and must be unique on the site; title is shown in the admin and
// the page editor; target is the key of the Publishing instance accepted
// proposals become draft posts in, for example "news". Add that instance to
// the app as well.
func Module(key, title, target string) webthings.Module {
	return webthings.Module{
		Type:   "submissions",
		Key:    key,
		Title:  title,
		Schema: schema(),
		Setup: func(env webthings.Env) (webthings.Parts, error) {
			return setup(env, target)
		},
		Funcs: funcs(),
		// The visitor forms themes render with form_field.
		Forms: []any{ProposalInput{}},
		Templates: []frontend.Template{
			{Name: "form", Data: FormView{}, Example: formExample},
		},
		Mail: mailTemplates(),
	}
}

func setup(env webthings.Env, target string) (webthings.Parts, error) {
	if target == "" || target == env.Key {
		return webthings.Parts{}, fmt.Errorf("submissions %q needs the key of a Publishing instance", env.Key)
	}

	service := &Service{
		key:    env.Key,
		target: target,
		db:     env.DB,
		media:  env.Media,
		drafts: func() (drafter, error) {
			posts, ok := env.Service(target).(*publishing.Service)
			if !ok || posts == nil {
				return nil, fmt.Errorf("%w: %q", ErrNoTarget, target)
			}

			return posts, nil
		},
		mail:          env.Mail,
		pages:         env.Pages,
		frontend:      env.Frontend,
		adminLanguage: env.AdminLanguage,
		baseURL:       env.AbsoluteURL,
		adminURL:      env.AdminURL,
		actions:       env.Actions(),
	}

	service.registerActions()

	return webthings.Parts{
		Admin:  []admin.Section{section(env, service)},
		Public: service.handler(),
		// Proposals carry an image, larger than core's default.
		ActionBodyLimit: bodyLimit,
		Service:         service,
	}, nil
}

func section(env webthings.Env, service *Service) admin.Section {
	return admin.Section{
		ID:    env.Key,
		Title: env.Title,
		Icon:  "megaphone",
		Files: files,
		Trash: service.trash(),
		// The badge counts the proposals that wait for a decision.
		Badge: func(ctx context.Context) int {
			count, err := service.Count(ctx, StatusNew)
			if err != nil {
				slog.ErrorContext(ctx, "count submissions", "module", env.Key, "error", err)
			}

			return count
		},
		Routes: func(routes *admin.Routes) {
			screens := screens{
				service: service,
				admin:   routes.Admin(),
				env:     env,
				routes:  routes,
			}

			routes.Get("", admin.View, screens.list).As("index")
			// Only editors who may save the settings see them: they hold the
			// address notifications go to.
			settings := screens.settingsScreen()
			routes.Get("/settings", admin.Edit, settings.Show).As("settings")
			routes.Post("/settings", admin.Edit, settings.Post)
			routes.Get("/{id}", admin.View, screens.show).As("show")
			routes.Post("/{id}/accept", admin.Publish, screens.accept).As("accept")
			routes.Post("/{id}/reject", admin.Publish, screens.reject).As("reject")
			routes.Post("/{id}/delete", admin.Delete, screens.delete).As("delete")
		},
	}
}

