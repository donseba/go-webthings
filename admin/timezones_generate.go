//go:build ignore

// This program writes zones.go, the time zones editors choose from, from the
// zone.tab file of the IANA time zone database (tzdata), which lists one
// zone per country region, such as Europe/Amsterdam for the Netherlands:
//
//	go run timezones_generate.go -tab /usr/share/zoneinfo/zone.tab
//
// zone.tab rather than zone1970.tab, because zone1970.tab merges countries
// that agree since 1970: it has no Europe/Amsterdam, only Europe/Brussels.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"
	"strings"
)

func main() {
	tab := flag.String("tab", "/usr/share/zoneinfo/zone.tab", "the zone.tab file of tzdata")
	out := flag.String("out", "zones.go", "the Go file to write")
	flag.Parse()

	zones, err := read(*tab)
	if err != nil {
		log.Fatal(err)
	}

	version, _ := os.ReadFile(strings.TrimSuffix(*tab, "zone.tab") + "+VERSION")

	var b bytes.Buffer

	fmt.Fprintf(
		&b,
		"// Code generated by timezones_generate.go from tzdata %s; DO NOT EDIT.\n\n",
		strings.TrimSpace(string(version)),
	)
	b.WriteString("package admin\n\n")
	b.WriteString("// zones are the time zones of the IANA database, one per country region,\n")
	b.WriteString("// sorted by name, and UTC.\n")
	b.WriteString("var zones = []string{\n")

	for _, zone := range zones {
		fmt.Fprintf(&b, "\t%q,\n", zone)
	}

	b.WriteString("}\n")

	source, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}

	if err := os.WriteFile(*out, source, 0o644); err != nil {
		log.Fatal(err)
	}
}

// read returns the zone names of zone.tab (its third column), with UTC.
func read(path string) ([]string, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	zones := []string{"UTC"}
	scanner := bufio.NewScanner(file)

	for scanner.Scan() {
		line := scanner.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}

		columns := strings.Split(line, "\t")
		if len(columns) < 3 {
			return nil, fmt.Errorf("%s: unexpected line %q", path, line)
		}

		zones = append(zones, columns[2])
	}

	if err := scanner.Err(); err != nil {
		return nil, err
	}

	slices.Sort(zones)

	return slices.Compact(zones), nil
}
