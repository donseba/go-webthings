// StyleScaffold is a starting point for assets/site.css, the stylesheet of
// the theme that LayoutScaffold links with {{styles}}.
func StyleScaffold() string {
	return `/*
    The theme's own styles, linked by the layout with {{styles}} after
    webthings.css and before the theme's settings (values.css), so the
    settings' custom properties, such as var(--accent), can be used here.
*/
`
}

// HeadScaffold is a starting point for regions/head.gohtml, the tags of
// the page in <head>, which the layout places with {{slot "head"}}: core's
// tags (webthings/head-tags.gohtml, see Templates) and room for the
// theme's own. Without the file, core's tags alone are the region.
func HeadScaffold() string {
	return `{{/* @dot ` + typeName(reflect.TypeFor[View]()) + ` */}}
{{- /*
    The tags of the page in <head>, placed by the layout with {{slot "head"}}.
    WebThings writes the title, description, canonical and alternate links,
    sharing tags, icons, feeds and structured data; add the theme's own
    tags below. An HTMX navigation replaces them with those of the page
    arrived at, and sets the document's title from the <title>.
*/ -}}
{{template "` + coreHead + `" .}}
{{/* For example: <meta name="theme-color" content="#336699"> */}}
`
}

func typeName(t reflect.Type) string {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}

	return t.PkgPath() + "." + t.Name()
}

func writeFields(b *strings.Builder, t reflect.Type, depth int, seen map[reflect.Type]bool) {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}

	if t.Kind() != reflect.Struct || seen[t] || depth > 4 {
		return
	}

	seen[t] = true
	defer delete(seen, t)

	indent := strings.Repeat("    ", depth)

	for _, field := range reflect.VisibleFields(t) {
		if !field.IsExported() || field.Anonymous || imagePart(t, field.Name) {
			continue
		}

		writeField(b, t, field, indent, depth, seen)
	}
}

func writeField(
	b *strings.Builder,
	parent reflect.Type,
	field reflect.StructField,
	indent string,
	depth int,
	seen map[reflect.Type]bool,
) {
	name := field.Name
	value := "." + name
	kind := field.Type.Kind()

	switch {
	case field.Type == htmlType:
		fmt.Fprintf(b, "%s<div>{{%s}}</div>\n", indent, value)
	case field.Type == timeType:
		fmt.Fprintf(
			b,
			"%s{{if not %s.IsZero}}<time datetime=\"{{%s.Format \"2006-01-02T15:04:05Z07:00\"}}\">{{date %s \"long\"}}</time>{{end}}\n",
			indent,
			value,
			value,
			value,
		)
	case kind == reflect.String && name == "Title":
		fmt.Fprintf(b, "%s<h%d>{{%s}}</h%d>\n", indent, min(depth, 3), value, min(depth, 3))
	case kind == reflect.String && name == "ID":
		fmt.Fprintf(b, "%s{{/* %s: {{%s}} — stable, usable as an anchor */}}\n", indent, name, value)
	case kind == reflect.String && strings.HasSuffix(name, "OriginalURL"):
		fmt.Fprintf(b, "%s{{/* %s: {{%s}} — the uploaded file, for a download link */}}\n", indent, name, value)
	case kind == reflect.String && strings.HasSuffix(name, "URL") && isImage(name):
		writeImage(b, parent, name, indent)
	case kind == reflect.String && strings.HasSuffix(name, "URL"):
		fmt.Fprintf(b, "%s{{with %s}}<a href=\"{{.}}\">%s</a>{{end}}\n", indent, value, name)
	case kind == reflect.String:
		fmt.Fprintf(b, "%s{{with %s}}<p>{{.}}</p>{{end}}\n", indent, value)
	case kind == reflect.Bool:
		fmt.Fprintf(b, "%s{{if %s}}<p>%s</p>{{end}}\n", indent, value, name)
	case kind >= reflect.Int && kind <= reflect.Float64:
		fmt.Fprintf(b, "%s<p>%s: {{%s}}</p>\n", indent, name, value)
	case kind == reflect.Slice && isStruct(field.Type.Elem()):
		fmt.Fprintf(b, "%s{{range %s}}\n%s    <article>\n", indent, value, indent)
		writeFields(b, field.Type.Elem(), depth+2, seen)
		fmt.Fprintf(b, "%s    </article>\n%s{{end}}\n", indent, indent)
	case kind == reflect.Slice:
		fmt.Fprintf(b, "%s{{range %s}}<span>{{.}}</span>{{end}}\n", indent, value)
	case isStruct(field.Type):
		fmt.Fprintf(b, "%s{{with %s}}\n%s    <section>\n", indent, value, indent)
		writeFields(b, field.Type, depth+2, seen)
		fmt.Fprintf(b, "%s    </section>\n%s{{end}}\n", indent, indent)
	default:
		fmt.Fprintf(b, "%s{{/* %s (%s) */}}\n", indent, name, field.Type)
	}
}

func isStruct(t reflect.Type) bool {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}

	return t.Kind() == reflect.Struct && t != timeType
}

// writeImage writes an img for the image field name, with the srcset module
// views give next to it (see Frontend.Image). Width and height are left to
// the theme: without CSS that scales images, they would fix the size.
func writeImage(b *strings.Builder, parent reflect.Type, name, indent string) {
	prefix := strings.TrimSuffix(name, "URL")

	fmt.Fprintf(b, "%s{{if .%s}}<img src=\"{{.%s}}\"", indent, name, name)

	if _, ok := parent.FieldByName(prefix + "Srcset"); ok {
		fmt.Fprintf(b, "{{with .%sSrcset}} srcset=\"{{.}}\" sizes=\"100vw\"{{end}}", prefix)
	}

	b.WriteString(" alt=\"\">{{end}}\n")
}

// imagePart reports whether the field name of t belongs to an image field:
// the srcset, width or height next to its URL, which writeImage uses or
// leaves to the theme.
func imagePart(t reflect.Type, name string) bool {
	for _, suffix := range []string{"Srcset", "Width", "Height"} {
		prefix, ok := strings.CutSuffix(name, suffix)
		if !ok || !isImage(prefix+"URL") {
			continue
		}

		if _, ok := t.FieldByName(prefix + "URL"); ok {
			return true
		}
	}

	return false
}

func isImage(name string) bool {
	for _, word := range []string{"Image", "Cover", "Photo", "Logo", "Favicon"} {
		if strings.Contains(name, word) {
			return true
		}
	}

	return false
}
