package frontend

import (
	"fmt"
	"html/template"
	"reflect"
	"strings"
	"time"
)

var (
	timeType = reflect.TypeFor[time.Time]()
	htmlType = reflect.TypeFor[template.HTML]()
)

// Scaffold is a starting point for a template: its go-clue contract and every
// field of its data, in plain HTML to build the design around.
func Scaffold(t Template) string {
	if t.Example != "" {
		return t.Example
	}

	data := reflect.TypeOf(t.Data)

	var b strings.Builder

	fmt.Fprintf(&b, "{{/* @dot %s */}}\n", typeName(data))
	b.WriteString("{{/* Starting point generated by WebThings: every field of the data is used below. */}}\n")
	b.WriteString("<main id=\"content\">\n")
	writeFields(&b, data, 1, map[reflect.Type]bool{})
	b.WriteString("</main>\n")

	return b.String()
}

